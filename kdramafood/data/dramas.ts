export function getDramaBySlug(slug: string): Drama | undefined {
  return dramas.find((d) => d.slug === slug);
}

export function getRecipeBySlug(slug: string): (Recipe & { drama: Drama }) | undefined {
  for (const drama of dramas) {
    const recipe = drama.recipes.find((r) => r.slug === slug);
    if (recipe) return { ...recipe, drama };
  }
  return undefined;
}

export function getAllRecipes(): (Recipe & { drama: Drama })[] {
  return dramas.flatMap((drama) =>
    drama.recipes.map((recipe) => ({ ...recipe, drama }))
  );
}

